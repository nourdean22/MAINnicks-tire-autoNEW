/**
 * watch-veo-cutover.mjs · READ-ONLY (2026-07-31)
 *
 * Watches the FIRST reel generated after REEL_VIDEO_PROVIDER was deleted from
 * Railway (auto-select now resolves to Veo, since GEMINI_API_KEY is present).
 *
 * The decisive signal is NOT the job status — it is the CLIP FILENAME, because
 * that is written by whichever provider actually ran:
 *   veo-<ts>-<rand>.mp4  → Veo   (downloadAndRehostVeoVideo)
 *   clip-<jobid>-<n>.mp4 → Higgsfield
 * A job can reach 'assembled' on either provider, so status alone would NOT
 * prove the cutover took effect.
 *
 * SAFETY: SELECT only.
 */
import mysql from "mysql2/promise";
import { readFileSync } from "node:fs";

const BASELINE = Number(process.argv[2] || 1200001);
const MAX_MIN = Number(process.argv[3] || 45);

const url = readFileSync("C:/Users/nourd/NOURCITY/apps/nickstire/.env", "utf8")
  .split(/\r?\n/).find((l) => l.startsWith("DATABASE_URL="))
  ?.slice("DATABASE_URL=".length).trim().replace(/^["']|["']$/g, "");

const conn = await mysql.createConnection({ uri: url, ssl: { rejectUnauthorized: true } });
const et = () => new Date(Date.now() - 4 * 3600_000).toISOString().slice(11, 19);

const providerOf = (clipsJson) => {
  let clips = [];
  try { clips = JSON.parse(clipsJson || "[]"); } catch { /* ignore */ }
  const names = clips.filter(Boolean).map((u) => String(u).split("/").pop() || "");
  if (!names.length) return { tag: "no clips yet", names };
  if (names.some((n) => n.startsWith("veo-"))) return { tag: "VEO", names };
  if (names.some((n) => n.startsWith("clip-"))) return { tag: "HIGGSFIELD", names };
  return { tag: `unrecognized (${names[0]})`, names };
};

const TERMINAL = new Set(["assembled", "published", "posted", "failed", "publish_ambiguous"]);
console.log(`\nwatching for reel jobs > #${BASELINE} · up to ${MAX_MIN}m · ${et()} ET`);
console.log("decisive signal = clip filename prefix (veo- vs clip-), not status\n");

const deadline = Date.now() + MAX_MIN * 60_000;
let verdict = null;

while (Date.now() < deadline && !verdict) {
  const [rows] = await conn.execute(
    `SELECT id, status, clipUrlsJson, error,
            DATE_FORMAT(CONVERT_TZ(createdAt,'+00:00','-04:00'),'%H:%i') AS made
       FROM reel_jobs WHERE id > ? ORDER BY id ASC`,
    [BASELINE],
  );
  if (rows.length) {
    for (const r of rows) {
      const p = providerOf(r.clipUrlsJson);
      console.log(`  ${et()} #${r.id} ${String(r.status).padEnd(11)} provider=${String(p.tag).padEnd(11)} clips=${p.names.length}${r.error ? `  ERR: ${String(r.error).slice(0, 90)}` : ""}`);
      if (p.names.length) console.log(`        first clip: ${p.names[0]}`);
      if (TERMINAL.has(r.status)) {
        verdict = { id: r.id, status: r.status, provider: p.tag, error: r.error };
        break;
      }
    }
  } else {
    console.log(`  ${et()} (no new job yet)`);
  }
  if (!verdict) await new Promise((r) => setTimeout(r, 60_000));
}

console.log("");
if (!verdict) {
  console.log(`VERDICT: TIMEOUT after ${MAX_MIN}m — no job reached a terminal state.`);
} else if (verdict.status === "failed") {
  console.log(`VERDICT: FAIL · #${verdict.id} failed on ${verdict.provider} — ${verdict.error}`);
} else if (verdict.provider === "VEO") {
  console.log(`VERDICT: PASS · #${verdict.id} reached '${verdict.status}' with clips generated by VEO — cutover confirmed.`);
} else {
  console.log(`VERDICT: MIXED · #${verdict.id} reached '${verdict.status}' but clips came from ${verdict.provider} — cutover did NOT take effect.`);
}
await conn.end();
