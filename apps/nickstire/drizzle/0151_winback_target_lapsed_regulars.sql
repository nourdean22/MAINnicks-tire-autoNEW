-- 0151 - winback_campaigns.targetSegment gains 'lapsed_regulars' (2026-10-25)
--
-- Win-Back can now target the lapsed regulars the Customers tab counts (3+ visits, last visit
-- 90 to 365 days ago; server/lib/customer-segments.ts lapsedRegularCondition). targetSegment is
-- an ENUM and TiDB runs STRICT_TRANS_TABLES, so until this is applied winback.create rejects a
-- 'lapsed_regulars' campaign with "Data truncated for column 'targetSegment'" (no row, no send).
--
-- APPEND-ONLY (0082, 0097, 0136, 0146, 0147): the member goes at the END so existing ordinals
-- are unchanged and TiDB treats this as a metadata-only change. Idempotent: re-running
-- re-asserts the same list. Hand-applied, or one tap on /admin Settings > Run Migrations
-- (routers/nick/intelligence.ts handleRunMigrations carries the same statement).
ALTER TABLE winback_campaigns MODIFY COLUMN targetSegment ENUM('lapsed','unknown','recent','dormant','lost','vip','fleet','tire_customer','lapsed_regulars') NOT NULL;
